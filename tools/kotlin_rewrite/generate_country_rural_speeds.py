#!/usr/bin/env python3
"""Generates CountryRuralSpeedData.kt: the default speed limit outside built-up areas, per country.

Italy's 90 km/h (the limit of an ordinary extra-urban road) is the model: for every country the value
is the national default limit for an ordinary road outside built-up areas, in km/h.

Input is legal_default_speeds.json from https://github.com/westnordost/osm-legal-default-speeds
(demo/distribution/), itself built from https://wiki.openstreetmap.org/wiki/Default_speed_limits
(CC BY-SA 2.0). Usage:

    python3 -I generate_country_rural_speeds.py legal_default_speeds.json > CountryRuralSpeedData.kt
"""
import collections
import json
import re
import sys


def kmh(value):
    match = re.fullmatch(r"(\d{1,3})(?:\s*(mph))?", (value or "").strip())
    if not match:
        return None
    number = int(match.group(1))
    return round(number * 1.609344) if match.group(2) else number


def rural_limit(entries):
    """The entry named "rural", else the country's unnamed default entry."""
    for wanted in ("rural", None):
        for entry in entries:
            if entry.get("name") == wanted:
                limit = kmh(entry["tags"].get("maxspeed"))
                if limit is not None:
                    return limit
    return None


def main(path):
    data = json.load(open(path, encoding="utf-8"))
    meta = data["meta"]
    table = data["speedLimitsByCountryCode"]
    countries, states, regions = {}, {}, collections.defaultdict(list)
    for code, entries in sorted(table.items()):
        limit = rural_limit(entries)
        if limit is None:
            continue
        if "-" not in code:
            countries[code] = limit
        elif code.startswith("US-"):
            states[code[3:]] = limit
        else:
            regions[code.split("-")[0]].append(limit)
    # A country described only by its subdivisions (Canada) takes their most common value; the
    # United States by its states, since geonames names those by postal code.
    for code, limits in regions.items():
        countries.setdefault(code, collections.Counter(limits).most_common(1)[0][0])
    countries.setdefault("US", collections.Counter(states.values()).most_common(1)[0][0])
    median = sorted(countries.values())[len(countries) // 2]
    world = 5 * round(median / 5)  # 89 -> 90, which is Italy's value

    out = sys.stdout
    out.write("// Generated by tools/kotlin_rewrite/generate_country_rural_speeds.py. Do not edit.\n")
    out.write(f"// Source: OpenStreetMap wiki \"Default speed limits\", revision {meta['revisionId']}\n")
    out.write(f"// ({meta['timestamp']}), {meta['license']}; see THIRD_PARTY_NOTICES.md.\n")
    out.write("package app.roadstr.core.navigation\n\n")
    out.write("/** Default speed limit outside built-up areas on an ordinary road, km/h, by country and US state. */\n")
    out.write("object CountryRuralSpeedData {\n")
    out.write("    /** Median of the countries below (rounded to 5), for a country the wiki has no value for. */\n")
    out.write(f"    const val WORLD_MEDIAN_KMH = {world}\n\n")
    for name, mapping in (("byCountry", countries), ("byUsState", states)):
        out.write(f"    val {name}: Map<String, Int> = mapOf(\n")
        for code in sorted(mapping):
            out.write(f'        "{code}" to {mapping[code]},\n')
        out.write("    )\n\n" if name == "byCountry" else "    )\n")
    out.write("}\n")


if __name__ == "__main__":
    main(sys.argv[1])
